    /**
     * Requires webhooks:read on the owning practice or pharmacy key. Lists platform webhook grants in the key's mode. Platforms cannot list or grant themselves delegated access.
     *
     * @param ListGrantsRequest $request
     * @param ?array{
     *   baseUrl?: string,
     *   maxRetries?: int,
