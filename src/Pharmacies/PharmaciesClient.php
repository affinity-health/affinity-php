<?php

namespace Affinity\Pharmacies;

use Psr\Http\Client\ClientInterface;
use Affinity\Core\Client\RawClient;
use Affinity\Pharmacies\Requests\ListPharmaciesRequest;
use Affinity\Types\ListPharmaciesResponse;
